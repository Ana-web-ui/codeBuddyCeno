import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const output = resolve('.vercel/output');
const config = JSON.parse(readFileSync(resolve(output, 'config.json'), 'utf8'));
assert.equal(config.version, 3);
const functionRoot = resolve(output, 'functions/__server.func');
const runtime = JSON.parse(readFileSync(resolve(functionRoot, '.vc-config.json'), 'utf8'));
const { default: app } = await import(pathToFileURL(resolve(functionRoot, runtime.handler)).href);
const response = await app.fetch(new Request('https://code-buddy-ceno.vercel.app/'));
const html = await response.text();
assert.equal(response.status, 200, 'A função deve renderizar a página sem erro.');
assert.match(html, /Configure seu projeto/);
assert.doesNotMatch(html, /This page couldn.t load/);
const assets = [...new Set([...html.matchAll(/(?:src|href)="(\/_next\/static\/[^"?]+)/g)].map(match => match[1]))];
assert.ok(assets.length > 0, 'O HTML deve referenciar arquivos estáticos.');
for (const asset of assets) assert.ok(existsSync(resolve(output, 'static', asset.slice(1))), `Arquivo ausente: ${asset}`);
console.log(JSON.stringify({ status: response.status, runtime: runtime.runtime, htmlBytes: Buffer.byteLength(html), assets: assets.length }));
